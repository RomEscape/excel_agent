/**
 * Excel Live 복합 자연어를 단계별 명령으로 분해한다.
 * 예: "C3에 777 입력하고 D열 0이하는 파란색 표시 후 저장해줘"
 */
//: 전면 보류 — 라우터 `_UNIVERSAL_HOLD_ABSOLUTE` 와 같은 뜻(CLAUDE.md §6).
const WHOLE_SENTENCE_HOLD =
  /아무\s*(?:것|거|작업|일|짓)?\s*도?\s*(?:안\s*(?:해|하|건드)|하지\s*(?:마|말|않)|실행하지\s*(?:마|말|않)|만지지\s*(?:마|말))|(?:일단|지금은?|그냥|오늘은?|당분간|우선)\s*보류|보류(?:하자|하겠|할게|할래|합시다|해요|하죠|하기로)/i;

export function splitExcelCompositeCommand(rawMessage) {
  // 줄바꿈은 살린다. 사람이 값을 여러 줄로 붙여넣으면("지역,주문건수⏎수도권,10452 입력해줘")
  // 줄이 곧 표의 행이다 — 공백으로 뭉개면 사이드카가 한 줄로 받아 칸이 밀린다
  // (2026-08-19 붙여넣기 흐름 강건화). 가로 공백만 하나로 줄인다.
  const text = String(rawMessage ?? "")
    .replace(/\r\n?/g, "\n")
    .replace(/[^\S\n\t]+/g, " ")
    .replace(/\n{2,}/g, "\n")
    .trim();
  if (!text) return [];
  // 값 격자(쉼표·세미콜론·탭·줄바꿈 셋 이상 + 끝의 쓰기 동사)는 한 명령이다 — 값 속 "성실하고", "그리고"로
  // 쪼개면 표 절반이 잘려 나간다(2026-08-19 ex17 실측: 11행 붙여넣기가 "…우수, 성실"에서 끊겼다).
  if (looksLikeValueGrid(text)) return [text];
  // 문장 끝의 **전면 보류**가 앞 절을 지배한다 — 쪼개면 앞 조각이 보류를 못 보고
  // 실행해 버린다(2026-09-07 복합 배터리 실측: "…집계 내고 … 일단 보류할게.
  // 지금은 아무 작업도 하지 마"가 집계를 실행했다). 보류 문장은 통째로 넘긴다 —
  // 실제 noop 판정은 사이드카가 한다(CLAUDE.md §6 "전면 보류").
  if (WHOLE_SENTENCE_HOLD.test(text)) return [text];

  const separators = [
    /\s+그리고\s+/i,
    /\s+그리고나서\s+/i,
    /\s*하고나서\s*/i,
    /\s*한\s*다음(?:에)?\s*/i,
    /\s*한\s*뒤(?:에)?\s*/i,
    /\s*후에\s*/i,
    // "그 다음 줄에 …"의 다음은 순서가 아니라 자리다 — 줄·행·칸·열·시트·표가 뒤따르면 쪼개지 않는다
    // (2026-08-19 ex9 v2 실측: "아 그리고 …"가 "아" + 명령으로 갈려 "아"만 전송됐다).
    /\s+그\s*다음(?:으로)?\s+(?!(?:줄|행|칸|열|시트|탭|표|페이지|단계))/i,
    /\s+다음(?:으로)?\s+(?!(?:줄|행|칸|열|시트|탭|표|페이지|단계))/i,
    /\s+이후\s+/i,
    /\s*하고\s+/i,
    // "합계 내고 그래프", "…만 남기고 표시" — 하다형이 **아닌** 동사의 연결어미 `-고`.
    // 맨 `-고`로 쪼개면 "재고"·"보고서"·"참고"가 갈린다. 동작 동사를 통째로 뒤돌아보고
    // 그 **뒤의 공백**에서만 자른다 — 동사는 앞 조각에 남아 그 조각만으로 뜻이 선다.
    // `빼고`는 넣지 않는다: "전자 빼고 나머지"는 순서가 아니라 제외다.
    // `남기고`도 넣지 않는다 — "…만 남기고 빨갛게 표시"는 두 절이 **조건을 공유**해서
    // 쪼개면 양쪽 다 되묻기가 된다(2026-09-07 실측: 분리 전 1단계 실행 → 분리 후 되묻기 2회).
    // (2026-09-07 플래너 재측정: 이 문형 2건에서 앞 단계가 통째로 누락됐다.)
    /(?<=(?:내고|넣고|걸고|뽑고|만들고|지우고|바꾸고|채우고|매기고))\s+/i,
    /\s+then\s+/i,
    /\s+and then\s+/i,
  ];

  let parts = [text];
  for (const sep of separators) {
    parts = parts.flatMap((part) => part.split(sep));
  }

  return parts
    .map((p) => p.trim())
    .map((p) => p.replace(/^[,\s]+|[,\s]+$/g, ""))
    .filter(Boolean)
    // 추임새만 남은 조각("아", "음", "ㅇㅇ", "그럼")은 명령이 아니다 — 보내면 되묻기가 나고 뒤 조각이 막힌다.
    .filter((p) => !FILLER_ONLY_PART.test(p));
}

export function looksLikeValueGrid(text) {
  const t = String(text ?? "");
  const seps = (t.match(/[,;\t\n]/g) || []).length;
  return seps >= 3 && /(입력|기록|넣어|채워|써|적어)\s*(?:해)?\s*(?:줘요|줘|주세요|주라|줄래|놔|둬|봐|조|주십시오)?\s*[~.!?…]*\s*$/.test(t);
}

const FILLER_ONLY_PART =
  /^(?:(?:아|어|음|응|네|넵|옙|예|ㅇㅇ|ㅇㅋ|ㅋㅋ+|ㅎㅎ+|흠|오|아하|좋아|그래|ok|okay|그럼|자|그|이|저|일단|먼저|우선|그냥|아니|근데|그런데|그리고|그리구|또)[\s,.!~]*)+$/i;
